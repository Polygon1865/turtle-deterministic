def resolve(formula_id: str) -> Formula | None:
    """Return the definition for an id, or ``None`` when it is unknown."""
    explicit = EXPLICIT.get(formula_id)
    if explicit is not None:
        return explicit
    for prefix, expression, owner in PREFIXES:
        if formula_id.endswith(prefix) if prefix.startswith(".") else formula_id.startswith(prefix):
            return Formula(
                formula_id=formula_id,
                expression=expression,
                inputs=(),
                owner=owner,
                note="前缀规则（按行/因子生成）。",
            )
    return None


def unknown(ids: Iterable[str]) -> list[str]:
    return sorted(formula_id for formula_id in ids if formula_id and resolve(formula_id) is None)


def describe(formula_id: str) -> str:
    formula = resolve(formula_id)
    if formula is None:
        return f"{formula_id}（未登记）"
    return f"{formula.formula_id} = {formula.expression}"
