"""Formula registry: every ``MetricPoint.formula_id`` must resolve here.

Roadmap W2.4.  The point of the registry is not to compute anything — the
computation lives in the factor engine — but to answer "what does this number
mean, which inputs produced it, and who owns it" with one lookup.  Docs and
the audit can then cite a formula id instead of prose.

Ids are either explicit (one row per formula) or generated by a prefix rule
(``statement.income.revenue``, ``factor.r``, ``policy.max_debt_ratio``, …).
``tests/test_formula_registry.py`` fails when a new literal id is emitted
without a definition here.
"""

