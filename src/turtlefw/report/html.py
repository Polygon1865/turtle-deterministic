"""Minimal, dependency-free Markdown → HTML for reports.

Only the constructs used by ``analysis_report.md`` / ``data_pack.md`` are
supported: headings, paragraphs, lists, tables, blockquotes, bold and code.
The goal is a readable local HTML artifact, not a general Markdown engine.
"""

from __future__ import annotations

import html
import re
from pathlib import Path

_BOLD = re.compile(r"\*\*(.+?)\*\*")
_CODE = re.compile(r"`([^`]+)`")
_LINK = re.compile(r"\[([^\]]+)\]\((https?://[^)]+)\)")


def _inline(text: str) -> str:
    escaped = html.escape(text, quote=False)
    escaped = _LINK.sub(r'<a href="\2">\1</a>', escaped)
    escaped = _BOLD.sub(r"<strong>\1</strong>", escaped)
    escaped = _CODE.sub(r"<code>\1</code>", escaped)
    return escaped


def _cells(line: str) -> list[str]:
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def _is_separator(line: str) -> bool:
    cells = _cells(line)
    return bool(cells) and all(set(cell) <= set(":- ") for cell in cells)


def markdown_to_html(
    markdown_text: str,
    *,
    title: str = "Turtle Report",
    chart_html: str = "",
) -> str:
    lines = markdown_text.splitlines()
    out: list[str] = [
        "<!DOCTYPE html>",
        '<html lang="zh-CN"><head><meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        f"<title>{html.escape(title)}</title>",
        "<style>",
        "body{font-family:system-ui,-apple-system,'Segoe UI',sans-serif;max-width:1100px;"
        "margin:2rem auto;padding:0 1rem;line-height:1.65;color:#1f2328;background:#fff}",
        "h1,h2,h3{line-height:1.3} h2{border-bottom:1px solid #d0d7de;padding-bottom:.3rem;margin-top:2rem}",
        "table{border-collapse:collapse;margin:1rem 0;width:100%;font-size:.93rem}",
        "th,td{border:1px solid #d0d7de;padding:.35rem .55rem;text-align:left;vertical-align:top}",
        "th{background:#f6f8fa} tr:nth-child(even) td{background:#fbfcfd}",
        "blockquote{border-left:4px solid #d0d7de;margin:1rem 0;padding:.2rem 1rem;color:#57606a}",
        "code{background:#f6f8fa;padding:.1rem .3rem;border-radius:4px}",
        "a{color:#0969da} .footer{margin-top:3rem;color:#8c959f;font-size:.85rem}",
        ".chart{margin:1rem 0 1.5rem} .chart svg{width:100%;height:auto;border:1px solid #d0d7de;border-radius:6px}",
        "</style></head><body>",
    ]
    if chart_html:
        out.append(chart_html)
    paragraph: list[str] = []
    in_list = False
    in_table = False

    def flush_paragraph() -> None:
        nonlocal paragraph
        if paragraph:
            out.append(f"<p>{_inline(' '.join(paragraph))}</p>")
            paragraph = []

    def close_list() -> None:
        nonlocal in_list
        if in_list:
            out.append("</ul>")
            in_list = False

    def close_table() -> None:
        nonlocal in_table
        if in_table:
            out.append("</table>")
            in_table = False

    for line in lines:
        stripped = line.strip()
        if not stripped:
            flush_paragraph()
            close_list()
            close_table()
            continue

        if stripped.startswith("|") and stripped.endswith("|"):
            flush_paragraph()
            close_list()
            if _is_separator(stripped):
                continue
            cells = _cells(stripped)
            if not in_table:
                out.append("<table>")
                out.append("<tr>" + "".join(f"<th>{_inline(c)}</th>" for c in cells) + "</tr>")
                in_table = True
            else:
                out.append("<tr>" + "".join(f"<td>{_inline(c)}</td>" for c in cells) + "</tr>")
            continue

        close_table()
        if stripped.startswith("#"):
            flush_paragraph()
            close_list()
            level = min(len(stripped) - len(stripped.lstrip("#")), 6)
            out.append(f"<h{level}>{_inline(stripped[level:].strip())}</h{level}>")
            continue

        if stripped.startswith(">"):
            flush_paragraph()
            close_list()
            out.append(f"<blockquote>{_inline(stripped[1:].strip())}</blockquote>")
            continue

        if stripped.startswith(("- ", "* ")):
            flush_paragraph()
            if not in_list:
                out.append("<ul>")
                in_list = True
            out.append(f"<li>{_inline(stripped[2:])}</li>")
            continue

        paragraph.append(stripped)

    flush_paragraph()
    close_list()
    close_table()
    out.append('<div class="footer">Generated by turtle-framework · deterministic report</div>')
    out.append("</body></html>")
    return "\n".join(out)


def convert_file(
    input_path: Path | str,
    output_path: Path | str,
    *,
    title: str = "Turtle Report",
    chart_html: str | None = None,
) -> Path:
    source = Path(input_path)
    target = Path(output_path)
    if chart_html is None:
        from .charts import chart_for

        chart_html = chart_for(source)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        markdown_to_html(
            source.read_text(encoding="utf-8"),
            title=title,
            chart_html=chart_html,
        ),
        encoding="utf-8",
    )
    return target
